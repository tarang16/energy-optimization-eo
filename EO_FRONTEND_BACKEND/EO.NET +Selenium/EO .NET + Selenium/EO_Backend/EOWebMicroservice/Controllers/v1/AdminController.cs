        /// <summary>
        /// To decrypt JWT generated by authenticate api
        /// </summary>
        /// <param name="model"></param>
        /// <returns></returns>
        [HttpPost("getPlainToken")]
        [ProducesResponseType(typeof(Response<object>), StatusCodes.Status200OK)]
        public IActionResult GetPlainToken([FromBody] Token model)
        {
            CryptographyHelper crypt = new CryptographyHelper(_jwtSettings);
            return Ok(new Response<object>(crypt.AesGcmDecrypt(model.value!)));
        }



