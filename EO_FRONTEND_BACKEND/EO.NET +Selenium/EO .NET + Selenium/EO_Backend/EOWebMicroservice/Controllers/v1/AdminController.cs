            }
        }


        /// <summary>
        /// To modify status, assigned to for an error
        /// </summary>
        /// <param name="request"></param>
        /// <returns></returns>
        [HttpPost("modify_error_status_by_error_id")]
        public async Task<IActionResult> ModifyErrorStatusByErrorID([FromBody] ModifyErrorStatusByErrorIDRequest request)
        {
            int errorID;
            if (int.TryParse(request.errorID, out errorID))
            {
                errorID = int.Parse(request.errorID);
            }
            else
            {
                return BadRequest(new Response<Array>(ResponseConstants.CUSTOMERROR, $"Invalid errorID type", ResponseConstants.EMPTYDATA));
            }
            string status = request.status!;
            string assignedTo = request.assignedTo!;
            var validStatus = await _adminServices.GetValidErrorStatusList();

            if (!validStatus.Exists(item => item.Equals(status, StringComparison.CurrentCultureIgnoreCase)))
            {
                return BadRequest(new Response<Array>(ResponseConstants.CUSTOMERROR, $"Invalid status type '{request.status}' Allowed fields: {validStatus[0]}, {validStatus[1]}, {validStatus[2]}", ResponseConstants.EMPTYDATA));
            }
            var ModifyErrorStatusresult = await _adminServices.ModifyErrorStatusByErrorID(errorID, status, assignedTo);
            return Ok(new Response<object>(ModifyErrorStatusresult));
        }


